/**
 * مستقبل کے Multi-Tenant اور Multi-User نظام کی بنیاد — صرف اقسام اور اصول
 *
 * اس مرحلے میں یہاں کوئی ڈیٹا بیس نہیں، کوئی لاگ اِن نہیں، اور کوئی اجازت نافذ نہیں
 * کی گئی۔ یہ فائل صرف یہ طے کرتی ہے کہ جب اگلے مرحلوں میں یہ نظام بنے گا تو
 * پروگرامنگ کس شکل میں ہوگی، تاکہ ہر شعبہ شروع سے اسی ڈھانچے پر بنے۔
 *
 * اصول (منظور شدہ منصوبے کے مطابق):
 * 1. ہر مدرسہ ایک الگ Tenant ہے۔ اس کا اپنا اکاؤنٹ اور اپنا ڈیٹا ہوگا۔
 * 2. ڈیٹا بیس کے ہر ریکارڈ کے ساتھ اس کے مدرسے کی شناخت (madrasaId) لکھی جائے گی۔
 * 3. ہر درخواست پر صرف اسی مدرسے کا ڈیٹا دیا جائے گا — دوسرے مدرسے کا ڈیٹا
 *    نہ دکھایا جائے گا، نہ تلاش میں آئے گا، نہ کسی فائل یا رپورٹ میں شامل ہوگا۔
 * 4. طالبات کے شعبے کا ڈیٹا صرف ان صارفین کو نظر آئے گا جنہیں اس کی خاص اجازت ملی ہو۔
 * 5. Super Admin بھی کسی مدرسے کا نجی ڈیٹا بلا اجازت نہیں دیکھے گا۔
 * 6. مالی ریکارڈ کبھی مستقل حذف نہیں ہوگا؛ درستگی الٹ اندراج (reversal) سے ہوگی۔
 */

/** ایک مدرسہ (ایک Tenant) — مستقبل میں ڈیٹا بیس کی میز بنے گی، ابھی صرف شکل طے ہے۔ */
export interface Madrasa {
  /** ہر مدرسے کی مستقل شناخت */
  id: string;
  /** مدرسے کا نام، مثلاً «مدرسہ سیدہ عائشہ صدیقہ (رضی اللہ عنہا) للبنات» */
  name: string;
  /** فعال یا غیر فعال (فیس/آزمائش کی مدت ختم ہونے پر غیر فعال ہو سکتا ہے) */
  isActive: boolean;
}

/** نظام کے کردار — ہر صارف کا ایک کردار ہوگا (مستقبل کا لاگ اِن نظام) */
export type MadrasaRole =
  | "super_admin" // نظام کا نگران (صرف حمید)
  | "mohtamim" // مہتمم
  | "nazim_taleemat" // ناظمِ تعلیمات
  | "muhasib" // محاسب
  | "mudarris" // مدرس
  | "clerk"; // کلرک

/** ایک صارف — مستقبل میں ڈیٹا بیس کی میز اور لاگ اِن نظام بنے گا */
export interface MadrasaUser {
  id: string;
  /** صارف کس مدرسے سے تعلق رکھتا ہے — یہی علیحدگی کی بنیاد ہے */
  madrasaId: string;
  name: string;
  role: MadrasaRole;
}

/** ایک اجازت: کون سا کردار کس شعبے میں کیا کر سکتا ہے */
export interface Permission {
  role: MadrasaRole;
  /** شعبے کی شناخت، مثلاً ‎"students"‎ یا ‎"fees"‎ */
  moduleId: string;
  canView: boolean;
  canCreate: boolean;
  canEdit: boolean;
  canApprove: boolean;
}

/**
 * ہر ڈیٹا ریکارڈ کے ساتھ مدرسے کی شناخت لازمی ہوگی۔
 * مستقبل میں ڈیٹا بیس کی ہر میز اسی شکل پر بنے گی۔
 */
export interface TenantOwned {
  /** ریکارڈ کس مدرسے کا ہے */
  madrasaId: string;
}
