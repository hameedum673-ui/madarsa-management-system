-- 066 — ہجری تاریخ کی درستگی (پاکستان کے حساب سے)
-- حسابی ہجری تاریخ چاند دیکھنے کے سرکاری اعلان سے ایک دن آگے/پیچھے ہو سکتی ہے؛
-- مالک عمومی ریکارڈ میں یہ ترتیب بدل سکتا ہے (-1 = ایک دن پیچھے، 0 = درست، 1 = ایک دن آگے)۔
-- پیش فرض 0 (حسابی تاریخ)؛ ہر مدرسہ اپنی ترتیب خود رکھتا ہے۔
alter table public.madrasa_profile
  add column if not exists hijri_offset integer not null default 0
  check (hijri_offset in (-1, 0, 1));
